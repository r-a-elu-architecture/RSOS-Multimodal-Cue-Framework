"""Generate model/PREDICTIONS.md: what the formal learning model says about the Override Protocol.

Run:  python model/predictions.py
Deterministic; no randomness. Parameters are swept rather than fixed, so each
prediction is reported with how robust it is to the assumed saliences and rate.
"""
import itertools
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from rsx import conditioning as cm  # noqa: E402

BUNDLES = {"V": ["V"], "VA": ["V", "A"], "VAK": ["V", "A", "K"], "VAKO": ["V", "A", "K", "O"], "VAKOG": ["V", "A", "K", "O", "G"]}
SCALES = [0.5, 0.75, 1.0, 1.5]          # multiply all saliences
BETAS = [0.3, 0.5, 0.7]


def alpha(scale):
    return {k: v * scale for k, v in cm.DEFAULT_ALPHA.items()}


def run():
    rows = []
    for s, b in itertools.product(SCALES, BETAS):
        a = alpha(s)
        if sum(a[c] for c in BUNDLES["VAKOG"] + ["trigger"]) * b >= 2:
            continue  # unstable learning-rate region for RW; skipped
        for name, ch in BUNDLES.items():
            acq = cm.acquisition(ch, 200, a, b)
            fresh = cm.counterconditioning(ch, 0, 40, -0.8, a, b)
            pre = cm.counterconditioning(ch, 30, 40, -0.8, a, b)
            rows.append({
                "scale": s, "beta": b, "bundle": name,
                "trials_to_90": cm.trials_to(acq, "compound", 0.9),
                "single_min_end": acq[-1]["single_min"],
                "trigger_fresh_10": fresh[9]["V_trigger"], "trigger_fresh_40": fresh[-1]["V_trigger"],
                "trigger_pre_10": pre[9]["V_trigger"], "trigger_pre_40": pre[-1]["V_trigger"],
            })
    return rows


def main():
    rows = run()
    base = [r for r in rows if r["scale"] == 1.0 and r["beta"] == 0.5]
    settings = sorted({(r["scale"], r["beta"]) for r in rows})

    def holds(pred):
        return sum(1 for st in settings if pred([r for r in rows if (r["scale"], r["beta"]) == st])), len(settings)

    by = lambda rs: {r["bundle"]: r for r in rs}
    p1 = holds(lambda rs: all(by(rs)[x]["trials_to_90"] >= by(rs)[y]["trials_to_90"] for x, y in zip(BUNDLES, list(BUNDLES)[1:])))
    p2 = holds(lambda rs: all(by(rs)[x]["single_min_end"] > by(rs)[y]["single_min_end"] for x, y in zip(BUNDLES, list(BUNDLES)[1:])))
    p3 = holds(lambda rs: all(r["trigger_fresh_40"] > r["trigger_pre_40"] for r in rs))
    p4 = holds(lambda rs: all(r["trigger_pre_40"] < -0.3 for r in rs if r["bundle"] != "V"))
    p5 = holds(lambda rs: by(rs)["V"]["trigger_fresh_40"] > by(rs)["VAKOG"]["trigger_fresh_40"])

    h = cm.habit(400)
    days = {lvl: next(r["run"] for r in h if r["automaticity"] >= lvl) for lvl in (0.5, 0.8, 0.95)}

    L = []
    w = L.append
    w("# Override Protocol: formal model predictions\n")
    w("Generated by `model/predictions.py` from `rsx/conditioning.py`. **These are predictions of a model, not data.** "
      "They make the protocol's claims precise so that human studies can confirm or refute them.\n")
    w(f"Parameter sweep: salience scale {SCALES} × learning rate β {BETAS} = {len(settings)} stable settings. "
      "Default saliences: " + ", ".join(f"{k} {v}" for k, v in cm.DEFAULT_ALPHA.items()) + ".\n")
    w("## At the default setting (scale 1.0, β 0.5)\n")
    w("| Bundle | Runs to 90% of the agency state | Weakest single channel after 200 runs | Trigger valence after 10 / 40 pairings, bundle not pre-trained | Same, bundle pre-trained 30 runs |")
    w("|---|---:|---:|---:|---:|")
    for r in base:
        w(f"| {r['bundle']} | {r['trials_to_90']} | {r['single_min_end']:.3f} | {r['trigger_fresh_10']:+.3f} / {r['trigger_fresh_40']:+.3f} | {r['trigger_pre_10']:+.3f} / {r['trigger_pre_40']:+.3f} |")
    w("\nTrigger valence starts at −0.80 (the trigger predicts distress). Positive means the trigger now predicts the agency state.\n")
    w("## Predictions and how robust they are\n")
    w("| # | Prediction | Holds in | What it means for the protocol |")
    w("|---|---|---:|---|")
    w(f"| P1 | Adding channels reaches the full agency state in fewer runs (V ≥ VA ≥ VAK ≥ VAKO ≥ VAKOG) | {p1[0]}/{p1[1]} | Supports multichannel tiers (spec H3) |")
    w(f"| P2 | Each single channel ends *weaker* the more channels share the bundle (overshadowing) | {p2[0]}/{p2[1]} | A single cue alone (just the word, just the scent) recalls less than the full bundle: practise and test with the whole bundle |")
    w(f"| P3 | If the bundle is practised first, the trigger itself gains less positive value (blocking) | {p3[0]}/{p3[1]} | Stage A acquisition makes the routine reliable but limits counterconditioning of the trigger |")
    w(f"| P4 | With a pre-trained multichannel bundle, the trigger stays clearly negative (< −0.30) after 40 pairings: the bundle compensates for it instead of changing it | {p4[0]}/{p4[1]} | Pairing alone makes the routine reliable but does not by itself change how the trigger feels |")
    w(f"| P5 | A single-channel routine transfers more value to the trigger than a full VAKOG bundle | {p5[0]}/{p5[1]} | Trade-off: rich bundles give a strong state but compete with the trigger for learning |")
    w("\n## Habit (trigger → routine)\n")
    w(f"With η = 0.035 per trigger-paired run, automaticity reaches 0.5 after {days[0.5]} runs, 0.8 after {days[0.8]} and 0.95 after {days[0.95]}. "
      "At about one real trigger a day this is in the range Lally et al. (2010) observed for everyday habits (median 66 days to 95% of asymptote, range 18–254).\n")
    w("## Design consequences to test\n")
    w("1. **Two separate outcomes.** The reflex (trigger starts the routine) is a habit; the change in how the trigger feels is counterconditioning. Measure both: latency/SRBAI and trigger distress *before* running the routine.")
    w("2. **Changing the trigger needs more than pairing** (P3–P5). Candidate additions to test: interleave stages A and B rather than finishing A first; begin each run with a brief, tolerable moment of the trigger alone before \"I move, I act\" (in this model, non-reinforced trigger exposure is what moves its value toward zero); fade the bundle to fewer channels once the routine is reliable.")
    w("3. **Test cues alone and together.** A single-channel recall test after training is a direct check of P2.")
    w("4. **H3 is a two-sided bet.** The model predicts faster state induction with more channels (P1) but less trigger revaluation (P5). A human study that measures both outcomes can tell which matters more.\n")
    w("Model limits: Rescorla–Wagner treats each run as one compound trial, so it ignores that the trigger comes *before* the routine (serial order), as well as context, spontaneous recovery and reconsolidation. Real saliences are unknown and differ between people.")
    (HERE / "PREDICTIONS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
