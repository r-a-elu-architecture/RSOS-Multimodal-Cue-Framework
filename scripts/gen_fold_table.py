"""Generate the fold table (spec/FIXES_R6.md §3) from this Python's Unicode data, so that fold() is identical in Python and
in every browser whatever their Unicode version. Writes rsso/rsso/foldtable.py and docs/js/foldtable.js.
python3 scripts/gen_fold_table.py     (Python 3.13: Unicode 15.1; another version would change the pinned table)
"""
import json
import pathlib
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
# Look-alike letters (FIXES_R5 §3, extended by FIXES_R6 §3): Cyrillic, Greek, Turkish, Latin and Armenian.
LOOK_FROM = "авеорсухіјѕԁһӏԛԝАВЕКМНОРСТХУІЈЅԚԜαοινκρτυχΑΒΕΖΗΙΚΜΝΟΡΤΥΧıİɑɡɩȷօսցⅼ"
LOOK_TO = "abeopcyxijsdhlqwABEKMHOPCTXYIJSQWaoivkptuxABEZHIKMNOPTYXiIagijougl"


def table():
    assert len(LOOK_FROM) == len(LOOK_TO)
    marks, mapping = [], {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if unicodedata.category(c) == "Mn":
            marks.append(cp)
            continue
        d = "".join(x for x in unicodedata.normalize("NFKD", c) if unicodedata.category(x) != "Mn")
        if d != c and d and all(32 <= ord(x) < 127 for x in d):
            mapping[cp] = d
    for a, b in zip(LOOK_FROM, LOOK_TO):
        mapping[ord(a)] = b
    ranges = []
    for cp in marks:
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return unicodedata.unidata_version, ranges, dict(sorted(mapping.items()))


def main():
    version, ranges, mapping = table()
    head = f"Generated by scripts/gen_fold_table.py from Unicode {version}; do not edit (spec/FIXES_R6.md §3)."
    (ROOT / "rsso/rsso/foldtable.py").write_text(
        f'"""{head}"""\nUNICODE = "{version}"\nMARKS = {json.dumps(ranges, separators=(",", ":"))}\n'
        f"MAP = {{{','.join(f'{k}:{json.dumps(v)}' for k, v in mapping.items())}}}\n", encoding="utf-8")
    (ROOT / "docs/js/foldtable.js").write_text(
        f"/* {head} */\n(function (root) {{ root.RSOSFoldTable = {{ UNICODE: \"{version}\", MARKS: {json.dumps(ranges, separators=(',', ':'))},\n"
        f"  MAP: {{{','.join(f'{k}:{json.dumps(v)}' for k, v in mapping.items())}}} }};\n"
        f"  if (typeof module !== \"undefined\") module.exports = root.RSOSFoldTable; }})(typeof window !== \"undefined\" ? window : globalThis);\n",
        encoding="utf-8")
    print(f"Unicode {version}: {len(mapping)} mapped, {len(ranges)} mark ranges")


if __name__ == "__main__":
    main()
